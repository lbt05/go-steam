package main

import (
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/types/pluginpb"
)

func main() {
	opts := &protogen.Options{}
	opts.Run(Handler)
}

func Handler(p *protogen.Plugin) error {
	p.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)

	for _, f := range p.Files {
		if !f.Generate || len(f.Enums) == 0 {
			continue
		}

		g := p.NewGeneratedFile(f.GeneratedFilenamePrefix+"_extensions.pb.go", f.GoImportPath)
		g.P("// Code generated by protoc-gen-enums. DO NOT EDIT.")
		g.P()
		g.P("package ", f.GoPackageName)
		g.P()
		g.P("import (")
		g.P(`	"net/url"`)
		g.P(`	"strconv"`)
		g.P(")")
		g.P()

		for _, enum := range f.Enums {
			g.P("// EncodeValues implements the query.Encoder interface for ", enum.GoIdent.GoName, ".")
			g.P("// This allows the enum to be encoded as its numerical value in URL parameters.")
			g.P("func (x ", enum.GoIdent.GoName, ") EncodeValues(key string, v *url.Values) error {")
			g.P(`	v.Add(key, strconv.FormatInt(int64(x), 10))`)
			g.P(`	return nil`)
			g.P("}")
			g.P()
		}
	}

	return nil
}
