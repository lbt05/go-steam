package client

import (
	"context"
	"fmt"

	"github.com/lewisgibson/go-steam/language/steam"
	"github.com/lewisgibson/go-steam/protocol"
	"google.golang.org/protobuf/proto"
)

// Logon logs the client into Steam using a steamID and refresh token.
func (c *Client) Logon(ctx context.Context) error {
	identity, err := c.identity.Identity(ctx)
	if err != nil {
		return fmt.Errorf("failed to get identity: %w", err)
	}

	return c.protocol.Send(
		ctx,
		&protocol.Header{
			EMsg: steam.EMsg_k_EMsgClientLogon,
			Proto: &steam.CMsgProtoBufHeader{
				Steamid:     proto.Uint64(identity.SteamID().Uint64()),
				JobidSource: proto.Uint64(protocol.JOBID_NONE),
				JobidTarget: proto.Uint64(protocol.JOBID_NONE),
			},
		},
		&steam.CMsgClientLogon{
			ProtocolVersion:           proto.Uint32(65580),
			AccessToken:               proto.String(identity.RefreshToken()),
			SupportsRateLimitResponse: proto.Bool(true),
			MachineName:               proto.String(""),
			ObfuscatedPrivateIp: &steam.CMsgIPAddress{
				Ip: &steam.CMsgIPAddress_V4{V4: 0},
			},
			ClientLanguage: proto.String("english"),
			ClientOsType:   proto.Uint32(4294967093), // -203 as uint32 (Windows)
			ChatMode:       proto.Uint32(2),
			CellId:         proto.Uint32(85),
			MachineId: []byte{
				0x00, 0x4D, 0x65, 0x73, 0x73, 0x61, 0x67, 0x65, 0x4F, 0x62, 0x6A, 0x65, 0x63, 0x74, 0x00, 0x01,
				0x42, 0x42, 0x33, 0x00, 0x67, 0x6F, 0x2D, 0x73, 0x74, 0x65, 0x61, 0x6D, 0x2D, 0x63, 0x6C, 0x69,
				0x65, 0x6E, 0x74, 0x2D, 0x6D, 0x61, 0x63, 0x68, 0x69, 0x6E, 0x65, 0x2D, 0x69, 0x64, 0x2D, 0x68,
				0x65, 0x78, 0x61, 0x64, 0x65, 0x63, 0x69, 0x6D, 0x61, 0x6C, 0x00, 0x01, 0x46, 0x46, 0x32, 0x00,
				0x38, 0x36, 0x65, 0x35, 0x62, 0x62, 0x33, 0x30, 0x31, 0x35, 0x61, 0x39, 0x64, 0x61, 0x65, 0x61,
				0x65, 0x39, 0x31, 0x38, 0x39, 0x30, 0x62, 0x64, 0x39, 0x35, 0x34, 0x64, 0x38, 0x34, 0x37, 0x38,
				0x36, 0x61, 0x66, 0x33, 0x64, 0x63, 0x63, 0x31, 0x00, 0x01, 0x33, 0x42, 0x33, 0x00, 0x67, 0x6F,
				0x2D, 0x73, 0x74, 0x65, 0x61, 0x6D, 0x2D, 0x75, 0x75, 0x69, 0x64, 0x2D, 0x68, 0x65, 0x78, 0x2D,
				0x76, 0x61, 0x6C, 0x75, 0x65, 0x2D, 0x66, 0x6F, 0x72, 0x2D, 0x6D, 0x61, 0x63, 0x68, 0x69, 0x6E,
				0x65, 0x00, 0x08, 0x08,
			},
		},
	)
}
